from __future__ import annotations

from typing import Any


def _segments(version: str) -> list[dict[str, Any]]:
    """每个配置版本切成 4 个传输段，段级校验值用于断点续传与完整应用校验。"""
    items = ["调度策略", "过滤规则", "DNS解析", "带宽策略"]
    return [
        {
            "段号": index,
            "配置项": name,
            "校验值": f"sha256:{version}-seg{index}",
            "状态": "已固化",
        }
        for index, name in enumerate(items, start=1)
    ]


def _snapshot(snap_id: int, node: str, version: str, seq: int, *, current: bool, time: str) -> dict[str, Any]:
    return {
        "id": snap_id,
        "节点编号": node,
        "配置版本号": version,
        "版本序号": seq,
        "状态": "当前版本" if current else "历史版本",
        "发起人": "平台管理员",
        "生成时间": time,
        "段总数": 4,
        "段清单": _segments(version),
    }


